//! Writes a fish `conf.d` snippet that maps Flux's resolved GTK theme
//! colours onto fish's `fish_color_*` language variables, plus a `fish_prompt`
//! override that pulls the prompt glyph colours from the same variables.
//!
//! The snippet is sourced by fish before `config.fish`, and is a no-op
//! outside Flux's embedded shell because every line is guarded by
//! `if set -q FLUX_THEME_FG`.

use super::theme::ThemeEnv;
use std::fs;
use std::io::Write;
use std::path::PathBuf;

/// Marker line written at the top of every snippet Flux generates.
/// Used to tell "our file" apart from a user's or another tool's file, so
/// we never silently destroy their content on first write.
const GENERATED_MARKER: &str = "# Generated by Flux from the active GTK/libadwaita theme.";

fn snippet_path() -> Option<PathBuf> {
    dirs::config_dir().map(|d| d.join("fish").join("conf.d").join("flux-theme.fish"))
}

/// Returns `true` if `path` contains a Flux-generated snippet (or does not
/// exist, in which case there is nothing to protect).
fn is_flux_generated(path: &std::path::Path) -> bool {
    std::fs::read_to_string(path)
        .map(|s| s.starts_with(GENERATED_MARKER))
        .unwrap_or(true)
}

/// Renames `path` to `path.bak` if it exists and was not written by Flux.
///
/// Idempotent: once `<path>.bak` exists, later calls do nothing, so a user
/// who disables and re-enables the feature keeps their original file.
fn backup_if_foreign(path: &std::path::Path) {
    if !path.is_file() || is_flux_generated(path) {
        return;
    }
    let mut backup = path.to_path_buf();
    backup.set_extension("fish.bak");
    if !backup.exists() {
        let _ = std::fs::rename(path, &backup);
    }
}

/// Renders the snippet body. `pub(crate)` so it can be unit-tested.
pub(crate) fn render_snippet(env: &ThemeEnv) -> String {
    let strip = |s: &str| s.trim_start_matches('#').to_string();

    let fg = strip(&env.fg);
    let accent = strip(&env.accent);
    let dim = blend_hex(&env.fg, &env.bg, 0.55);
    let palette: Vec<String> = env.palette.iter().map(|c| strip(c)).collect();

    let mut out = String::with_capacity(2048);
    out.push_str("# Generated by Flux from the active GTK/libadwaita theme.\n");
    out.push_str("# Do not edit by hand - it is rewritten on every theme change.\n");
    out.push_str("# Inactive unless FLUX_THEME_FG is set (Flux's embedded terminal)\n");
    out.push_str("if set -q FLUX_THEME_FG\n");

    let semantic: &[(&str, &str)] = &[
        ("fish_color_normal", &fg),
        ("fish_color_command", &accent),
        ("fish_color_keyword", &palette[5]),
        ("fish_color_param", &palette[4]),
        ("fish_color_quote", &palette[3]),
        ("fish_color_redirection", &palette[4]),
        ("fish_color_end", &palette[6]),
        ("fish_color_error", &palette[1]),
        ("fish_color_escape", &palette[5]),
        ("fish_color_operator", &palette[4]),
        ("fish_color_autosuggestion", &dim),
        ("fish_color_comment", &dim),
        ("fish_color_selection", &fg),
        ("fish_color_search_match", &accent),
        ("fish_color_history_current", &accent),
        ("fish_color_cwd", &accent),
        ("fish_color_cwd_root", &palette[1]),
        ("fish_color_valid_path", &palette[2]),
        ("fish_pager_color_progress", &dim),
        ("fish_pager_color_prefix", &accent),
        ("fish_pager_color_completion", &fg),
        ("fish_pager_color_description", &dim),
        ("fish_pager_color_selected_background", &accent),
        ("fish_pager_color_selected_foreground", &fg),
    ];

    for (name, value) in semantic {
        out.push_str(&format!("    set -g {} {}\n", name, value));
    }

    // ── Prompt override ─────────────────────────────────────────────────
    // Fish 4.x's built-in prompt draws `❯❯❯` from its own bundled theme and
    // ignores `fish_color_*`. We redefine `fish_prompt` so the glyph reads
    // from the same variables Flux just set. The shape matches the built-in
    // prompt the user was already seeing (`~ ❯❯❯`).
    //
    // `prompt_pwd` is a fish builtin: `~` for home, abbreviated path otherwise.
    // `$status` is captured first because `set -l` and `set_color` clobber it.
    out.push_str("\n");
    out.push_str("    function fish_prompt\n");
    out.push_str("        set -l last_status $status\n");
    out.push_str("        set_color $fish_color_cwd\n");
    out.push_str("        printf '%s' (prompt_pwd)\n");
    out.push_str("        set_color normal\n");
    out.push_str("        printf ' '\n");
    out.push_str("        if test $last_status -eq 0\n");
    out.push_str("            set_color $fish_color_command\n");
    out.push_str("        else\n");
    out.push_str("            set_color $fish_color_error\n");
    out.push_str("        end\n");
    out.push_str("        printf '❯❯❯ '\n");
    out.push_str("        set_color normal\n");
    out.push_str("    end\n");

    out.push_str("end\n");
    out
}

fn blend_hex(a: &str, b: &str, t: f64) -> String {
    let parse = |s: &str| -> Option<(u8, u8, u8)> {
        let s = s.trim_start_matches('#');
        if s.len() != 6 {
            return None;
        }
        Some((
            u8::from_str_radix(&s[0..2], 16).ok()?,
            u8::from_str_radix(&s[2..4], 16).ok()?,
            u8::from_str_radix(&s[4..6], 16).ok()?,
        ))
    };
    let (Some(a), Some(b)) = (parse(a), parse(b)) else {
        return a.trim_start_matches('#').to_string();
    };
    let t = t.clamp(0.0, 1.0);
    let mix = |x: u8, y: u8| ((x as f64) * (1.0 - t) + (y as f64) * t).round() as u8;
    format!(
        "{:02x}{:02x}{:02x}",
        mix(a.0, b.0),
        mix(a.1, b.1),
        mix(a.2, b.2)
    )
}

/// Writes `render_snippet(env)` to `~/.config/fish/conf.d/flux-theme.fish`,
/// atomically, on a background thread. All errors are ignored: fish may not
/// be installed, and the user may not want the snippet.
pub fn write_fish_theme_snippet(env: &ThemeEnv) {
    // Respect the user's choice. When off, do not rewrite the file (so a
    // user who disabled the feature keeps whatever state they had) and do
    // not create it.
    if !crate::utils::load_config().ui.fish_theme {
        return;
    }

    let Some(path) = snippet_path() else { return };
    let body = render_snippet(env);

    std::thread::Builder::new()
        .name("flux-fish-theme".into())
        .spawn(move || {
            if let Some(parent) = path.parent() {
                let _ = fs::create_dir_all(parent);
            }
            // Take a one-time backup of any foreign file at this path before
            // the first overwrite, so a user with a hand-edited or
            // third-party `flux-theme.fish` can recover their content.
            backup_if_foreign(&path);
            let tmp = path.with_extension("fish.tmp");
            if let Ok(mut f) = fs::File::create(&tmp) {
                if f.write_all(body.as_bytes()).is_ok() && f.sync_all().is_ok() {
                    let _ = fs::rename(&tmp, &path);
                } else {
                    let _ = fs::remove_file(&tmp);
                }
            }
        })
        .ok();
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample_env() -> ThemeEnv {
        ThemeEnv {
            fg: "#e5e5e5".into(),
            bg: "#1a1a1a".into(),
            accent: "#d34516".into(),
            palette: std::array::from_fn(|i| format!("#0000{:02x}", i as u8)),
            mode: "dark".into(),
        }
    }

    #[test]
    fn snippet_is_guarded_by_the_env_var() {
        let body = render_snippet(&sample_env());
        assert!(body.contains("if set -q FLUX_THEME_FG"));
        assert!(body.trim_end().ends_with("end"));
    }

    #[test]
    fn snippet_has_no_leading_hash_on_colours() {
        let body = render_snippet(&sample_env());
        for line in body.lines() {
            if let Some(rest) = line.trim().strip_prefix("set -g fish_color_") {
                let value = rest.split_whitespace().nth(1).unwrap_or("");
                assert!(!value.starts_with('#'), "raw hex leaked into: {line}");
            }
        }
    }

    #[test]
    fn snippet_defines_a_themed_prompt() {
        let body = render_snippet(&sample_env());
        assert!(body.contains("function fish_prompt"));
        assert!(body.contains("$fish_color_cwd"));
        assert!(body.contains("$fish_color_command"));
        assert!(body.contains("$fish_color_error"));
        // The prompt must be inside the FLUX_THEME_FG guard, not after it.
        let guard = body.find("if set -q FLUX_THEME_FG").unwrap();
        let prompt = body.find("function fish_prompt").unwrap();
        assert!(prompt > guard, "fish_prompt must be inside the guard");
    }

    #[test]
    fn blend_midpoint_is_between() {
        assert_eq!(blend_hex("#ffffff", "#000000", 0.5), "808080");
    }

    #[test]
    fn generated_marker_matches_first_line() {
        // Guards against a stale GENERATED_MARKER that would make
        // `is_flux_generated` reject Flux's own files.
        let body = render_snippet(&sample_env());
        assert!(body.starts_with(GENERATED_MARKER));
    }

    #[test]
    fn foreign_file_is_backed_up() {
        let dir =
            std::env::temp_dir().join(format!("flux-fish-backup-test-{}", std::process::id()));
        let _ = std::fs::create_dir_all(&dir);
        let path = dir.join("flux-theme.fish");
        let _ = std::fs::write(
            &path,
            "# user's hand-written theme\nset -g fish_color_normal red\n",
        );

        backup_if_foreign(&path);

        assert!(!path.exists(), "foreign file should be renamed");
        let backup = dir.join("flux-theme.fish.bak");
        assert!(backup.exists(), "backup should exist");
        let content = std::fs::read_to_string(&backup).unwrap();
        assert!(content.contains("user's hand-written"));

        // Second call is a no-op (backup already exists).
        let _ = std::fs::write(&path, "# another foreign file\n");
        backup_if_foreign(&path);
        assert_eq!(
            std::fs::read_to_string(&backup).unwrap(),
            content,
            "existing backup must not be overwritten"
        );

        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn flux_generated_file_is_not_backed_up() {
        let dir =
            std::env::temp_dir().join(format!("flux-fish-nobackup-test-{}", std::process::id()));
        let _ = std::fs::create_dir_all(&dir);
        let path = dir.join("flux-theme.fish");
        let _ = std::fs::write(&path, format!("{}\n# old snippet\n", GENERATED_MARKER));

        backup_if_foreign(&path);

        assert!(path.exists(), "generated file stays in place");
        assert!(!dir.join("flux-theme.fish.bak").exists());

        let _ = std::fs::remove_dir_all(&dir);
    }
}
