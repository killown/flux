//! Renderers for the generated fish files: `completions/flux-fm.fish` and
//! `data/fish/flux-integration.fish`.

use crate::args::CLI_OPTIONS;
use std::fmt::Write as _;

const GENERATED: &str = "# Generated by `cargo run --bin gen-docs`. Do not edit by hand.\n";

/// One option parsed out of a [`CLI_OPTIONS`] flag string.
struct Parsed<'a> {
    short: Option<char>,
    long: Option<&'a str>,
    takes_value: bool,
}

fn parse_flags(flags: &str) -> Parsed<'_> {
    let mut parsed = Parsed {
        short: None,
        long: None,
        takes_value: false,
    };
    for word in flags.split_whitespace() {
        let word = word.trim_end_matches(',');
        if let Some(long) = word.strip_prefix("--") {
            parsed.long = Some(long);
        } else if let Some(short) = word.strip_prefix('-') {
            parsed.short = short.chars().next();
        } else {
            // A bare word after the flag (`PATH`, `TARGET`, `IMAGE`) is a value.
            parsed.takes_value = true;
        }
    }
    parsed
}

fn fish_quote(s: &str) -> String {
    format!("'{}'", s.replace('\\', "\\\\").replace('\'', "\\'"))
}

/// Returns the complete `completions/flux-fm.fish`.
pub fn render_completions() -> String {
    let mut out = String::from(GENERATED);
    out.push_str("# Fish completions for flux-fm. Install to fish's `vendor_completions.d`\n");
    out.push_str("# or `~/.config/fish/completions/`.\n\n");

    for (flags, description) in CLI_OPTIONS {
        let parsed = parse_flags(flags);
        let mut line = String::from("complete -c flux-fm");
        if let Some(short) = parsed.short {
            let _ = write!(line, " -s {short}");
        }
        if let Some(long) = parsed.long {
            let _ = write!(line, " -l {long}");
        }
        if parsed.takes_value {
            // Every valued option takes filesystem paths.
            line.push_str(" -r -F");
        }
        let _ = write!(line, " -d {}", fish_quote(description));
        out.push_str(&line);
        out.push('\n');
    }

    out.push_str("\n# The help text calls the binary `flux`.\n");
    out.push_str("complete -c flux -w flux-fm\n");
    out
}

/// Returns the complete `data/fish/flux-integration.fish`.
pub fn render_integration() -> String {
    let mut out = String::from(GENERATED);
    out.push_str("# Fish helpers for Flux: flux_selection, flux_cwd, flux_goto, $F, $FN,\n");
    out.push_str("# $FD and $FCWD. Install to fish's `vendor_conf.d` (or source it from\n");
    out.push_str("# config.fish) to use them in any terminal, not only Flux's own.\n\n");
    out.push_str(&crate::shell_functions::render_functions());
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn assert_in_sync(generated: String, path: &str) {
        let committed = std::fs::read_to_string(path)
            .unwrap_or_else(|_| panic!("{path} is missing; run `cargo run --bin gen-docs`"));
        assert_eq!(
            generated, committed,
            "\n{path} is stale.\nRun `cargo run --bin gen-docs` to regenerate it."
        );
    }

    #[test]
    fn completions_are_in_sync() {
        assert_in_sync(render_completions(), "completions/flux-fm.fish");
    }

    #[test]
    fn integration_is_in_sync() {
        assert_in_sync(render_integration(), "data/fish/flux-integration.fish");
    }

    #[test]
    fn every_option_has_a_completion() {
        let out = render_completions();
        for (flags, _) in CLI_OPTIONS {
            let long = parse_flags(flags)
                .long
                .expect("every option has a long form");
            assert!(
                out.contains(&format!(" -l {long} ")),
                "no completion for --{long}"
            );
        }
    }

    #[test]
    fn valued_options_complete_paths() {
        let out = render_completions();
        let line = out.lines().find(|l| l.contains(" -l set-icon ")).unwrap();
        assert!(line.contains(" -r -F "));
        let line = out.lines().find(|l| l.contains(" -l no-sidebar ")).unwrap();
        assert!(!line.contains(" -r "));
    }

    #[test]
    fn quotes_are_escaped() {
        assert_eq!(fish_quote("it's"), "'it\\'s'");
    }
}
