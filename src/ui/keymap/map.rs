use super::constants;
use super::parse::parse_trigger;
use crate::model::ShortcutsConfig;

/// A collection of resolved GTK `ShortcutTrigger`s.
#[derive(Debug)]
#[allow(dead_code)]
pub struct KeyMap {
    pub quit: gtk::ShortcutTrigger,
    pub open: gtk::ShortcutTrigger,
    pub delete: gtk::ShortcutTrigger,
    pub back: gtk::ShortcutTrigger,
    pub forward: gtk::ShortcutTrigger,
    pub refresh: gtk::ShortcutTrigger,
    pub search: gtk::ShortcutTrigger,
    pub properties: gtk::ShortcutTrigger,
    pub toggle_hidden: gtk::ShortcutTrigger,
    pub settings: gtk::ShortcutTrigger,
    pub menu_editor: gtk::ShortcutTrigger,
    pub root: gtk::ShortcutTrigger,
    pub change_icon: gtk::ShortcutTrigger,
    pub reset_icon: gtk::ShortcutTrigger,
    pub toggle_terminal: gtk::ShortcutTrigger,
    pub copy_path: gtk::ShortcutTrigger,
    pub create_symlink: gtk::ShortcutTrigger,
    pub create_hardlink: gtk::ShortcutTrigger,
    pub toggle_folders_first: gtk::ShortcutTrigger,
    pub toggle_header: gtk::ShortcutTrigger,
    pub home: gtk::ShortcutTrigger,
    pub new_tab: gtk::ShortcutTrigger,
    pub close_tab: gtk::ShortcutTrigger,
    pub next_tab: gtk::ShortcutTrigger,
    pub prev_tab: gtk::ShortcutTrigger,
    pub toggle_statusbar: gtk::ShortcutTrigger,
    pub toggle_sidebar: gtk::ShortcutTrigger,
    pub toggle_filter_bar: gtk::ShortcutTrigger,
    pub cycle_filter_mode: gtk::ShortcutTrigger,
    pub filter_by_mime: gtk::ShortcutTrigger,
    pub toggle_wide_preview: gtk::ShortcutTrigger,
    pub open_debug_window: gtk::ShortcutTrigger,
    pub undo: gtk::ShortcutTrigger,
    pub redo: gtk::ShortcutTrigger,
    pub toggle_tag_panel: gtk::ShortcutTrigger,
    pub toggle_actions_panel: gtk::ShortcutTrigger,
    pub toggle_connect_panel: gtk::ShortcutTrigger,
    pub toggle_location_panel: gtk::ShortcutTrigger,
    pub toggle_list_mode: gtk::ShortcutTrigger,
    pub copy: gtk::ShortcutTrigger,
    pub cut: gtk::ShortcutTrigger,
    pub paste: gtk::ShortcutTrigger,
    pub cycle_sort: gtk::ShortcutTrigger,
    pub toggle_sort_order: gtk::ShortcutTrigger,
    pub cycle_by_letter_reanchor: gtk::ShortcutTrigger,
    pub cycle_by_letter_cancel: gtk::ShortcutTrigger,
}

impl KeyMap {
    pub fn new(config: &ShortcutsConfig) -> Self {
        Self {
            quit: parse_trigger(&config.quit, constants::QUIT),
            open: parse_trigger(&config.open, constants::OPEN),
            delete: parse_trigger(&config.delete, constants::DELETE),
            back: parse_trigger(&config.back, constants::BACK),
            forward: parse_trigger(&config.forward, constants::FORWARD),
            refresh: parse_trigger(&config.refresh, constants::REFRESH),
            search: parse_trigger(&config.search, constants::SEARCH),
            properties: parse_trigger(&config.open_properties, constants::PROPERTIES),
            toggle_hidden: parse_trigger(&config.toggle_hidden, constants::TOGGLE_HIDDEN),
            settings: parse_trigger(&config.settings, constants::SETTINGS),
            menu_editor: parse_trigger(&config.menu_editor, constants::MENU_EDITOR),
            root: parse_trigger(&config.root, constants::ROOT),
            change_icon: parse_trigger(&config.change_icon, constants::CHANGE_ICON),
            reset_icon: parse_trigger(&config.reset_icon, constants::RESET_ICON),
            toggle_terminal: parse_trigger(&config.toggle_terminal, constants::TOGGLE_TERMINAL),
            copy_path: parse_trigger(&config.copy_path, "<Primary><Shift>c"),
            create_symlink: parse_trigger(&config.create_symlink, "<Primary><Shift>v"),
            create_hardlink: parse_trigger(&config.create_hardlink, "<Primary><Alt><Shift>v"),
            toggle_folders_first: parse_trigger(
                &config.toggle_folders_first,
                constants::TOGGLE_FOLDERS_FIRST,
            ),
            toggle_header: parse_trigger(&config.toggle_header, constants::TOGGLE_HEADER),
            home: parse_trigger(&config.home, constants::HOME),
            new_tab: parse_trigger(&config.new_tab, constants::NEW_TAB),
            close_tab: parse_trigger(&config.close_tab, constants::CLOSE_TAB),
            next_tab: parse_trigger(&config.next_tab, constants::NEXT_TAB),
            prev_tab: parse_trigger(&config.prev_tab, constants::PREV_TAB),
            toggle_statusbar: parse_trigger(&config.toggle_statusbar, constants::TOGGLE_STATUSBAR),
            toggle_sidebar: parse_trigger(&config.toggle_sidebar, constants::TOGGLE_SIDEBAR),
            toggle_filter_bar: parse_trigger(&config.toggle_filter_bar, constants::TOGGLE_FILTER_BAR),
            cycle_filter_mode: parse_trigger(&config.cycle_filter_mode, constants::CYCLE_FILTER_MODE),
            filter_by_mime: parse_trigger(&config.filter_by_mime, constants::FILTER_BY_MIME),
            toggle_wide_preview: parse_trigger(&config.toggle_wide_preview, constants::TOGGLE_WIDE_PREVIEW),
            open_debug_window: parse_trigger(&config.open_debug_window, constants::OPEN_DEBUG_WINDOW),
            undo: parse_trigger(&config.undo, constants::UNDO),
            redo: parse_trigger(&config.redo, constants::REDO),
            toggle_tag_panel: parse_trigger(&config.toggle_tag_panel, constants::TOGGLE_TAG_PANEL),
            toggle_actions_panel: parse_trigger(&config.toggle_actions_panel, constants::TOGGLE_ACTIONS_PANEL),
            toggle_connect_panel: parse_trigger(&config.toggle_connect_panel, constants::TOGGLE_CONNECT_PANEL),
            toggle_location_panel: parse_trigger(&config.toggle_location_panel, constants::TOGGLE_LOCATION_PANEL),
            toggle_list_mode: parse_trigger(&config.toggle_list_mode, constants::TOGGLE_LIST_MODE),
            copy: parse_trigger(&config.copy, constants::COPY),
            cut: parse_trigger(&config.cut, constants::CUT),
            paste: parse_trigger(&config.paste, constants::PASTE),
            cycle_sort: parse_trigger(&config.cycle_sort, constants::CYCLE_SORT),
            toggle_sort_order: parse_trigger(&config.toggle_sort_order, constants::TOGGLE_SORT_ORDER),
            cycle_by_letter_reanchor: parse_trigger(&config.cycle_by_letter_reanchor, constants::CYCLE_BY_LETTER_REANCHOR),
            cycle_by_letter_cancel: parse_trigger(&config.cycle_by_letter_cancel, constants::CYCLE_BY_LETTER_CANCEL),
        }
    }
}
